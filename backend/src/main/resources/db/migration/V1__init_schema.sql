create table users (
    id bigint generated by default as identity primary key,
    username varchar(255) not null unique,
    email varchar(255) not null unique,
    password varchar(255) not null,
    enabled boolean not null,
    created_at timestamp not null,
    updated_at timestamp not null
);

create table exercises (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    name varchar(255) not null,
    description text not null,
    muscle_group varchar(255) not null,
    equipment varchar(255),
    image_url varchar(255),
    notes text,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_exercises_user foreign key (user_id) references users(id) on delete cascade
);

create index idx_exercises_user_id on exercises(user_id);

create table workouts (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    name varchar(255) not null,
    description text,
    goal varchar(255),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_workouts_user foreign key (user_id) references users(id) on delete cascade
);

create index idx_workouts_user_id on workouts(user_id);

create table workout_exercises (
    id bigint generated by default as identity primary key,
    workout_id bigint not null,
    exercise_id bigint not null,
    exercise_order integer not null,
    sets integer not null,
    reps integer not null,
    rest_seconds integer not null,
    notes text,
    constraint fk_workout_exercises_workout foreign key (workout_id) references workouts(id) on delete cascade,
    constraint fk_workout_exercises_exercise foreign key (exercise_id) references exercises(id),
    constraint uk_workout_exercises_workout_order unique (workout_id, exercise_order)
);

create index idx_workout_exercises_workout_id on workout_exercises(workout_id);
create index idx_workout_exercises_exercise_id on workout_exercises(exercise_id);

create table workout_schedules (
    id bigint generated by default as identity primary key,
    week_day varchar(255) not null,
    user_id bigint not null,
    workout_id bigint not null,
    constraint fk_workout_schedules_user foreign key (user_id) references users(id) on delete cascade,
    constraint fk_workout_schedules_workout foreign key (workout_id) references workouts(id) on delete cascade,
    constraint uk_workout_schedules_user_day unique (user_id, week_day)
);

create index idx_workout_schedules_workout_id on workout_schedules(workout_id);

